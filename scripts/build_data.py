"""Turns assets/manifest.json into data.js for the site (works over file:// without fetch)."""

from __future__ import annotations

import json
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
MANIFEST = SITE / "assets" / "manifest.json"
TARGET = SITE / "data.js"

# Tiles that do not hold up next to the rest of the work (blank pages, stray icons, screenshots).
EXCLUDE = {
    "ebook-nature-01",   # almost blank opening page
    "sichuan-opera-02",  # 48px icon
    "sichuan-opera-03",  # thin graphic sliver
    "yangtze-cableway-02",  # gradient placeholder slide
    "yangtze-cableway-03",  # website screenshot
    "yangtze-cableway-05",  # text screenshot
}

# Order of the opening image sequence (dark, graphic work reads best on black).
HERO = [
    "flower-gods-01",
    "postcards-04",
    "flower-gods-09",
    "sichuan-opera-01",
    "postcards-08",
    "flower-gods-05",
    "yangtze-cableway-06",
]

CATEGORY_ORDER = [
    "品牌设计",
    "编辑设计",
    "插画",
    "文化视觉",
    "信息可视化",
    "动态影像",
]


def main() -> None:
    items = json.loads(MANIFEST.read_text(encoding="utf-8"))
    kept = [item for item in items if Path(item["src"]).stem not in EXCLUDE]
    by_stem = {Path(item["src"]).stem: item for item in kept}

    hero = [by_stem[stem] for stem in HERO if stem in by_stem]
    categories = [name for name in CATEGORY_ORDER if any(item["category"] == name for item in kept)]

    # Interleave projects so the waterfall never runs one case study top-to-bottom.
    buckets: dict[str, list[dict]] = {}
    for item in kept:
        buckets.setdefault(item["slug"], []).append(item)
    order = sorted(buckets, key=lambda slug: kept.index(buckets[slug][0]))
    interleaved: list[dict] = []
    while any(buckets[slug] for slug in order):
        for slug in order:
            if buckets[slug]:
                interleaved.append(buckets[slug].pop(0))
    kept = interleaved

    payload = {"hero": hero, "items": kept, "categories": categories}
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    TARGET.write_text(
        "/* Generated by scripts/build_data.py — edit the source assets, not this file. */\n"
        f"window.PORTFOLIO = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {TARGET.name}: {len(kept)} tiles, {len(hero)} hero frames, {len(categories)} filters")


if __name__ == "__main__":
    main()
