"""Turns assets/manifest.json into data.js for the site (works over file:// without fetch)."""

from __future__ import annotations

import json
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
MANIFEST = SITE / "assets" / "manifest.json"
HERO_TRAIL = SITE / "assets" / "hero-trail.json"
TARGET = SITE / "data.js"

# Tiles that do not hold up next to the rest of the work (blank pages, stray icons, screenshots).
EXCLUDE = {
    "ebook-nature-01",   # almost blank opening page
}

# Fallback order for the opening cursor trail, used only when assets/hero-trail.json is absent.
FALLBACK_HERO = [
    "flower-gods-01",
    "postcards-04",
    "sichuan-opera-03",
    "flower-gods-09",
    "postcards-08",
    "sichuan-opera-02",
    "yangtze-cableway-01",
]

CATEGORY_ORDER = [
    "品牌设计",
    "编辑设计",
    "插画",
    "文化视觉",
    "信息可视化",
    "动态影像",
]

# Waterfall order: one project after another, exactly as the designer listed them.
SLUG_ORDER = [
    "flower-gods",        # 十二花神海报
    "postcards",          # 花神明信片
    "yangtze-cableway",   # 长江索道
    "sichuan-opera",      # 川剧变脸
    "brand-cis",          # 标志与 CIS 系统
    "illustration",       # 娃哈哈 AD 钙奶
    "ebook-nature",       # 重庆自然风貌电子书
    "solar-terms",        # 二十四节气
    "infovis-tea",        # 西湖龙井信息可视化
    "papercut",           # 剪纸
    "ganzhou",            # 赣州
    "motion-animals",     # 动物动态图形
    "dunhuang",           # 敦煌
]


def main() -> None:
    items = json.loads(MANIFEST.read_text(encoding="utf-8"))
    kept = [item for item in items if Path(item["src"]).stem not in EXCLUDE]
    by_stem = {Path(item["src"]).stem: item for item in kept}

    if HERO_TRAIL.exists():
        hero = json.loads(HERO_TRAIL.read_text(encoding="utf-8"))
    else:
        hero = [by_stem[stem] for stem in FALLBACK_HERO if stem in by_stem]
    categories = [name for name in CATEGORY_ORDER if any(item["category"] == name for item in kept)]

    # Group by project, in the order above; order inside a project stays as exported.
    buckets: dict[str, list[dict]] = {}
    for item in kept:
        buckets.setdefault(item["slug"], []).append(item)
    fallback = sorted(buckets, key=lambda slug: kept.index(buckets[slug][0]))
    order = [slug for slug in SLUG_ORDER if slug in buckets]
    order += [slug for slug in fallback if slug not in order]
    interleaved: list[dict] = []
    for slug in order:
        interleaved.extend(buckets[slug])
    kept = interleaved

    payload = {"hero": hero, "items": kept, "categories": categories}
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    TARGET.write_text(
        "/* Generated by scripts/build_data.py — edit the source assets, not this file. */\n"
        f"window.PORTFOLIO = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {TARGET.name}: {len(kept)} tiles, {len(hero)} hero frames, {len(categories)} filters")


if __name__ == "__main__":
    main()
